param(
    [Parameter(Mandatory=$true)]
    [guid]$ReportId,

    [Parameter(Mandatory=$true)]
    [string]$Recipient
)

$ErrorActionPreference = "Stop"

$base = "http://localhost:5075"
$apiRoot = Join-Path $PSScriptRoot "..\DailyStatus.Api"
$historyDir = Join-Path $apiRoot "DeliveryHistory"

New-Item -ItemType Directory -Force -Path $historyDir | Out-Null

if ($Recipient -notmatch '^[^@\s]+@[^@\s]+\.[^@\s]+$') {
    throw "Invalid recipient email."
}

$report = Invoke-RestMethod "$base/api/status/workflow/$ReportId"

if ($report.status -ne "Approved") {
    throw "Only approved reports can be emailed."
}

$recipientKey = $Recipient.Trim().ToLowerInvariant()

# Cross-process lock for report + recipient
$lockInput = "$ReportId|$recipientKey"
$sha256 = [System.Security.Cryptography.SHA256]::Create()
try {
    $sha = $sha256.ComputeHash(
        [System.Text.Encoding]::UTF8.GetBytes($lockInput)
    )
}
finally {
    $sha256.Dispose()
}
$lockHash = [BitConverter]::ToString($sha).Replace("-", "")
$mutexName = "Local\BrickredDailyStatusSend_$lockHash"

$mutex = [System.Threading.Mutex]::new($false, $mutexName)
$lockAcquired = $false

try {
    $lockAcquired = $mutex.WaitOne(
        [TimeSpan]::FromSeconds(10)
    )

    if (-not $lockAcquired) {
        throw "Another email send is already running for this report and recipient."
    }

$existing = Get-ChildItem $historyDir -Filter "*.json" |
    ForEach-Object {
        try {
            Get-Content $_.FullName -Raw | ConvertFrom-Json
        }
        catch {
            $null
        }
    } |
    Where-Object {
        $_.reportId -eq "$ReportId" -and
        $_.deliveryStatus -eq "Sent" -and
        $_.recipient -eq $recipientKey
    }

if ($existing) {
    throw "Duplicate blocked: This report was already emailed to $Recipient."
}

if (-not (Get-MgContext)) {
    Connect-MgGraph -Scopes "User.Read","Mail.Send" -NoWelcome
}

# Convert report Markdown into safe, formatted HTML
$lines = ([string]$report.summary) -split '\r?\n'
# Skip duplicate AI title and date already shown in email header
$lines = @($lines | Where-Object {
    $line = $_.Trim()

    $line -notmatch '^(?:\*\*)?Daily Status Report(?:\*\*)?$' -and
    $line -notmatch '^(?:\*\*)?Date:(?:\*\*)?\s*\d{4}-\d{2}-\d{2}$'
})

$formatted = New-Object System.Collections.Generic.List[string]
$inList = $false

foreach ($line in $lines) {
    $text = [System.Net.WebUtility]::HtmlEncode($line.Trim())

    $text = [regex]::Replace(
        $text,
        '\*\*(.+?)\*\*',
        '<strong>$1</strong>'
    )

    if ($text -match '^-\s+(.+)$') {
        if (-not $inList) {
            $formatted.Add('<ul>')
            $inList = $true
        }

        $formatted.Add("<li>$($Matches[1])</li>")
        continue
    }

    if ($inList) {
        $formatted.Add('</ul>')
        $inList = $false
    }

    if ([string]::IsNullOrWhiteSpace($text)) {
        continue
    }

    if ($text -eq '---') {
        $formatted.Add('<hr>')
        continue
    }

    if ($text -match '^###\s+(.+)$') {
        $formatted.Add("<h3>$($Matches[1])</h3>")
        continue
    }

    if ($text -match '^##\s+(.+)$') {
        $formatted.Add("<h2>$($Matches[1])</h2>")
        continue
    }

    if ($text -match '^#\s+(.+)$') {
        $formatted.Add("<h1>$($Matches[1])</h1>")
        continue
    }

    $formatted.Add("<p>$text</p>")
}

if ($inList) {
    $formatted.Add('</ul>')
}

$body = $formatted -join "`n"

$html = @"
<!DOCTYPE html>
<html>
<head>
<meta charset="UTF-8">
</head>
<body style="margin:0;padding:24px;background:#f3f5f9;font-family:Arial,sans-serif;">
<table role="presentation" style="max-width:720px;width:100%;margin:auto;background:#ffffff;border-collapse:collapse;">
<tr>
<td style="background:#101b30;padding:24px;color:#ffffff;">
<div style="font-size:22px;font-weight:bold;">
brickred<span style="color:#ef4050;">.</span>
</div>
<div style="font-size:12px;color:#cbd5e1;margin-top:6px;">
DAILY STATUS AGENT
</div>
</td>
</tr>
<tr>
<td style="padding:28px;color:#253247;font-size:14px;line-height:1.7;">
<h2 style="margin-top:0;">Daily Status Report</h2>
<p><strong>Report Date:</strong> $($report.reportDate)</p>
<hr style="border:0;border-top:1px solid #e2e8f0;">
$body
</td>
</tr>
<tr>
<td style="background:#f8fafc;padding:16px 28px;color:#64748b;font-size:12px;">
Generated by Brickred Daily Status Agent
</td>
</tr>
</table>
</body>
</html>
"@
$payload = @{
    message = @{
        subject = "Brickred Daily Status - $($report.reportDate)"
        body = @{
            contentType = "HTML"
            content = $html
        }
        toRecipients = @(
            @{
                emailAddress = @{
                    address = $recipientKey
                }
            }
        )
    }
    saveToSentItems = $true
} | ConvertTo-Json -Depth 10

Invoke-MgGraphRequest `
    -Method POST `
    -Uri "https://graph.microsoft.com/v1.0/me/sendMail" `
    -Body $payload `
    -ContentType "application/json"

$deliveryId = [guid]::NewGuid()

$record = @{
    deliveryId = "$deliveryId"
    reportId = "$ReportId"
    reportDate = "$($report.reportDate)"
    status = "Prepared"
    deliveryStatus = "Sent"
    channel = "Microsoft365"
    recipient = $recipientKey
    createdAtUtc = (Get-Date).ToUniversalTime().ToString("o")
    sentAtUtc = (Get-Date).ToUniversalTime().ToString("o")
    summary = [string]$report.summary
}

$record | ConvertTo-Json -Depth 6 |
    Set-Content -Path (Join-Path $historyDir "$deliveryId.json") -Encoding UTF8

Write-Host "SUCCESS: Microsoft Graph accepted email!" -ForegroundColor Green
Write-Host "Delivery history updated: Sent"
Write-Host "Recipient: $recipientKey"
}
finally {
    if ($lockAcquired) {
        $mutex.ReleaseMutex()
    }

    $mutex.Dispose()
}